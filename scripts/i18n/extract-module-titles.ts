/**
 * Regenerate the Portuguese and Spanish module-title files used by Cmd+K
 * lesson search and the review queue (src/data/moduleTitles.{pt,es}.ts).
 *
 * The curriculum overlays are lazy per-level chunks; search needs every
 * title at once without loading nine chunks, so the titles and subtitles are
 * copied into one small lazily-loaded file per language. The copy can never
 * drift silently: src/data/__tests__/moduleTitlesI18n.test.ts fails when a
 * file no longer matches the overlays and names this script.
 *
 * Run: npx tsx scripts/i18n/extract-module-titles.ts   (or npm run i18n:module-titles)
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MODULE_INDEX } from '../../src/data/moduleIndex';
import type { CurriculumLevelOverlay } from '../../src/i18n/content/types';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));

async function overlaysFor(lang: 'pt' | 'es'): Promise<CurriculumLevelOverlay['modules']> {
  const modules: CurriculumLevelOverlay['modules'] = {};
  for (let n = 1; n <= 9; n++) {
    const mod = (await import(`../../src/i18n/content/${lang}/curriculumL${n}.ts`)) as { default: CurriculumLevelOverlay };
    Object.assign(modules, mod.default.modules);
  }
  return modules;
}

async function main() {
  for (const lang of ['pt', 'es'] as const) {
    const modules = await overlaysFor(lang);
    const lines: string[] = [];
    for (const entry of MODULE_INDEX) {
      const ov = modules[entry.id];
      if (!ov) throw new Error(`${lang}: no overlay for ${entry.id}`);
      lines.push(`  ${entry.id}: [${JSON.stringify(ov.title)}, ${JSON.stringify(ov.subtitle)}],`);
    }
    const body = [
      '// GENERATED by scripts/i18n/extract-module-titles.ts from the curriculum',
      `// overlays (src/i18n/content/${lang}/curriculumL*.ts). Do not edit by hand:`,
      '// edit the overlay, then run `npm run i18n:module-titles`.',
      '',
      'const titles: Record<string, readonly [title: string, subtitle: string]> = {',
      ...lines,
      '};',
      '',
      'export default titles;',
      '',
    ].join('\n');
    const out = `${ROOT}src/data/moduleTitles.${lang}.ts`;
    writeFileSync(out, body, 'utf8');
    console.log(`wrote ${out} (${MODULE_INDEX.length} modules)`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
