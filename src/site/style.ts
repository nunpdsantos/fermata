/**
 * The search pages' one small stylesheet (/pages.css, not the app's bundle):
 * the app's own design tokens — read out of src/index.css at build time, so
 * the pages can never drift from the app's colours, type steps and tap size —
 * then the app's @font-face rules (Source Serif 4 and the accidentals face
 * from /fonts/), then the pages' own rules (scripts/pages/pages.css). Day
 * and night follow `prefers-color-scheme` (a page has no saved theme).
 */

/** The tokens the pages use: every one must be found in index.css, or the build fails. */
export const THEME_TOKENS = [
  '--font-serif', '--bg', '--card', '--card-hover', '--border', '--border-subtle',
  '--text', '--text-muted', '--text-dim', '--accent', '--accent-hover', '--on-accent', '--accent-text', '--focus-outline',
] as const;
export const TYPE_TOKENS = ['--text-caption', '--text-ui', '--text-body', '--text-title', '--text-display'] as const;

/** The body of the block that opens at `open` (the index of its `{`). */
function blockAt(css: string, open: number): string {
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}' && --depth === 0) return css.slice(open + 1, i);
  }
  throw new Error('site: index.css has an unclosed block');
}

/** The top-level blocks with this exact selector, in order. */
function blocks(css: string, selector: string): string[] {
  const out: string[] = [];
  const re = new RegExp(`(^|\\n)${selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*\\{`, 'g');
  for (const m of css.matchAll(re)) out.push(blockAt(css, (m.index ?? 0) + m[0].length - 1));
  return out;
}

function declaration(body: string, name: string): string | null {
  const m = body.match(new RegExp(`(?:^|[;{\\s])${name}\\s*:\\s*([^;]+);`));
  return m ? m[1].trim() : null;
}

export interface PageTokens {
  day: Record<string, string>;
  night: Record<string, string>;
  type: Record<string, string>;
  tap: string;
  tapCoarse: string;
  fontFaces: string[];
}

/** The tokens and @font-face rules, read from the app's index.css. Throws when one is missing. */
export function readTokens(indexCss: string): PageTokens {
  const dayBlock = blocks(indexCss, ':root').find((b) => /--bg\s*:/.test(b));
  const nightBlock = blocks(indexCss, ':root.fermata-night').find((b) => /--bg\s*:/.test(b));
  const typeBlock = blocks(indexCss, '@theme static')[0];
  const tapBlock = blocks(indexCss, ':root').find((b) => /--tap\s*:/.test(b));
  const coarse = indexCss.match(/@media \(pointer: coarse\)\s*\{\s*:root\s*\{\s*--tap:\s*([^;]+);\s*\}\s*\}/);
  if (!dayBlock || !nightBlock || !typeBlock || !tapBlock || !coarse) throw new Error('site: index.css no longer has the token blocks the pages read (:root, :root.fermata-night, @theme static, --tap, the coarse --tap)');
  const pick = (body: string, names: readonly string[], where: string) =>
    Object.fromEntries(names.map((n) => {
      const v = declaration(body, n);
      if (v === null) throw new Error(`site: index.css ${where} has no ${n}`);
      return [n, v];
    }));
  const fontFaces = [...indexCss.matchAll(/@font-face\s*\{/g)].map((m) => `@font-face {${blockAt(indexCss, (m.index ?? 0) + m[0].length - 1)}}`);
  if (fontFaces.length === 0) throw new Error('site: index.css has no @font-face');
  return {
    day: pick(dayBlock, THEME_TOKENS, ':root'),
    night: pick(nightBlock, THEME_TOKENS, ':root.fermata-night'),
    type: pick(typeBlock, TYPE_TOKENS, '@theme static'),
    tap: declaration(tapBlock, '--tap')!,
    tapCoarse: coarse[1].trim(),
    fontFaces,
  };
}

/** /pages.css: tokens (day, night by prefers-color-scheme, coarse pointer), the app's fonts, the pages' rules. */
export function pageStylesheet(indexCss: string, rules: string): string {
  const tk = readTokens(indexCss);
  const decls = (o: Record<string, string>) => Object.entries(o).map(([k, v]) => `  ${k}: ${v};`).join('\n');
  return `/* Fermatina's search pages. GENERATED by scripts/pages/build.ts: the tokens
   and fonts are the app's (src/index.css), the rules scripts/pages/pages.css. */
:root {
  color-scheme: light;
${decls(tk.day)}
${decls(tk.type)}
  --tap: ${tk.tap};
}
@media (prefers-color-scheme: dark) {
  :root {
    color-scheme: dark;
${decls(tk.night).replace(/^/gm, '  ')}
  }
}
@media (pointer: coarse) {
  :root { --tap: ${tk.tapCoarse}; }
}
${tk.fontFaces.join('\n')}
${rules.trim()}
`;
}
